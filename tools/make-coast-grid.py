#!/usr/bin/env python3
"""Coastal grid for the visual region (b175). Rules: design/look-library.md "글로벌 맥락".

Marks every 0.1° cell whose centre lies within KM (default 20) km of the Natural Earth 1:50m coastline (public domain,
ne_50m_coastline.geojson) and writes look/coast-grid.js (window.WX_COAST). Rows: hex(lat index + 900) ":" then runs
"<hex gap from previous run end>.<hex run length - 1>" over lon indices from -1800; rows joined by ";".
Usage: python3 tools/make-coast-grid.py <ne_50m_coastline.geojson> [km]
"""
import json, math, sys

STEP, LAT_MIN, LAT_MAX = 0.1, -56.0, 72.0


def cells(path, km):
    out = set()

    def mark(lat, lon):
        if not LAT_MIN - 1 <= lat <= LAT_MAX + 1:
            return
        c = math.cos(math.radians(lat))
        dlat, dlon = km / 111.0, km / (111.0 * max(0.05, c))
        for i in range(math.floor((lat - dlat) / STEP), math.floor((lat + dlat) / STEP) + 1):
            for j in range(math.floor((lon - dlon) / STEP), math.floor((lon + dlon) / STEP) + 1):
                x, y = ((j + .5) * STEP - lon) * 111 * c, ((i + .5) * STEP - lat) * 111
                if x * x + y * y <= km * km and LAT_MIN <= (i + .5) * STEP <= LAT_MAX:
                    out.add((i, (j + 1800) % 3600 - 1800))

    for f in json.load(open(path))["features"]:
        g = f["geometry"]
        for ln in g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]:
            for a, b in zip(ln, ln[1:]):
                d = math.hypot((b[0] - a[0]) * 111 * math.cos(math.radians(a[1])), (b[1] - a[1]) * 111)
                n = max(1, int(d / 2))  # a sample every ~2 km
                for k in range(n + 1):
                    t = k / n
                    mark(a[1] + (b[1] - a[1]) * t, a[0] + (b[0] - a[0]) * t)
    return out


def encode(cs):
    rows = {}
    for i, j in cs:
        rows.setdefault(i, []).append(j)
    out = []
    for i in sorted(rows):
        js, runs = sorted(rows[i]), []
        s = p = js[0]
        for j in js[1:]:
            if j == p + 1:
                p = j
                continue
            runs.append((s, p))
            s = p = j
        runs.append((s, p))
        prev, parts = -1800, []
        for s, e in runs:
            parts.append("%x.%x" % (s - prev, e - s))
            prev = e
        out.append("%x:" % (i + 900) + ",".join(parts))
    return ";".join(out)


if __name__ == "__main__":
    km = float(sys.argv[2]) if len(sys.argv) > 2 else 20
    data = encode(cells(sys.argv[1], km))
    with open("look/coast-grid.js", "w") as f:
        f.write("// b175: 0.1° cells within %g km of the coastline (Natural Earth 1:50m, public domain). "
                "Generated by tools/make-coast-grid.py, do not edit by hand.\n" % km)
        f.write("window.WX_COAST = { step: 0.1, km: %g, rows: \"%s\" };\n" % (km, data))
    print(len(data))
